#!/usr/bin/env python3
"""
Generates 6x6 Sudoku puzzles (digits 1-6, boxes are 2 rows x 3 cols)
with guaranteed-unique solutions, and emits them as a C header for the
GBA Sudoku game.

Box layout (box index = (row//2)*3 + (col//3)):
  Row 0-1 -> box row 0, Row 2-3 -> box row 1, Row 4-5 -> box row 2
  Col 0-2 -> box col 0, Col 3-5 -> box col 1
"""
import random
import sys

N = 6
BOX_H = 2  # box height in rows
BOX_W = 3  # box width in cols


def box_of(r, c):
    return (r // BOX_H) * (N // BOX_W) + (c // BOX_W)


def candidates_ok(grid, r, c, v):
    for i in range(N):
        if grid[r][i] == v or grid[i][c] == v:
            return False
    br = (r // BOX_H) * BOX_H
    bc = (c // BOX_W) * BOX_W
    for i in range(br, br + BOX_H):
        for j in range(bc, bc + BOX_W):
            if grid[i][j] == v:
                return False
    return True


def find_empty(grid):
    best = None
    best_count = 99
    for r in range(N):
        for c in range(N):
            if grid[r][c] == 0:
                opts = [v for v in range(1, N + 1) if candidates_ok(grid, r, c, v)]
                if len(opts) < best_count:
                    best_count = len(opts)
                    best = (r, c, opts)
                    if best_count == 0:
                        return best
    return best


def solve_random(grid):
    """Fill grid completely using randomized backtracking. Mutates grid."""
    cell = find_empty(grid)
    if cell is None:
        return True
    r, c, opts = cell
    random.shuffle(opts)
    for v in opts:
        grid[r][c] = v
        if solve_random(grid):
            return True
        grid[r][c] = 0
    return False


def count_solutions(grid, limit=2):
    """Count solutions up to `limit` (early exit). Does not mutate input."""
    g = [row[:] for row in grid]
    count = 0

    def rec():
        nonlocal count
        if count >= limit:
            return
        cell = find_empty(g)
        if cell is None:
            count += 1
            return
        r, c, opts = cell
        for v in opts:
            g[r][c] = v
            rec()
            g[r][c] = 0
            if count >= limit:
                return

    rec()
    return count


def make_full_solution():
    grid = [[0] * N for _ in range(N)]
    solve_random(grid)
    return grid


def make_puzzle(solution, target_givens):
    puzzle = [row[:] for row in solution]
    cells = [(r, c) for r in range(N) for c in range(N)]
    random.shuffle(cells)
    givens = N * N
    for (r, c) in cells:
        if givens <= target_givens:
            break
        saved = puzzle[r][c]
        puzzle[r][c] = 0
        if count_solutions(puzzle, limit=2) == 1:
            givens -= 1
        else:
            puzzle[r][c] = saved
    return puzzle, givens


def fmt_grid(grid, name):
    rows = []
    for r in grid:
        rows.append("  {" + ",".join(str(v) for v in r) + "}")
    return "{\n" + ",\n".join(rows) + "\n}"


def main():
    random.seed(1337)  # reproducible output
    num_puzzles = 12
    # roughly increasing difficulty (fewer givens = harder) across the set
    target_givens_list = [20, 19, 18, 18, 17, 17, 16, 16, 15, 15, 14, 14]

    puzzles = []
    solutions = []
    actual_givens = []

    attempts_log = []
    for i in range(num_puzzles):
        target = target_givens_list[i]
        sol = make_full_solution()
        puz, givens = make_puzzle(sol, target)
        # sanity re-check: puzzle must have exactly one solution
        assert count_solutions(puz, limit=2) == 1, f"puzzle {i} not unique!"
        puzzles.append(puz)
        solutions.append(sol)
        actual_givens.append(givens)
        attempts_log.append(f"puzzle {i}: target_givens={target} actual_givens={givens}")

    print("\n".join(attempts_log), file=sys.stderr)

    out = []
    out.append("// Auto-generated by tools/gen_puzzles.py — DO NOT EDIT BY HAND.")
    out.append("// 6x6 Sudoku puzzles (digits 1-6, 0 = empty). Each puzzle has a")
    out.append("// verified UNIQUE solution. Box layout: 2 rows x 3 cols per box.")
    out.append("#ifndef PUZZLES_DATA_H")
    out.append("#define PUZZLES_DATA_H")
    out.append("")
    out.append(f"#define NUM_PUZZLES {num_puzzles}")
    out.append(f"#define GRID_N {N}")
    out.append("")
    out.append(f"static const unsigned char puzzle_givens[NUM_PUZZLES][GRID_N][GRID_N] = {{")
    out.append(",\n".join(fmt_grid(p, f"puzzle_{i}") for i, p in enumerate(puzzles)))
    out.append("};")
    out.append("")
    out.append(f"static const unsigned char puzzle_solutions[NUM_PUZZLES][GRID_N][GRID_N] = {{")
    out.append(",\n".join(fmt_grid(s, f"solution_{i}") for i, s in enumerate(solutions)))
    out.append("};")
    out.append("")
    out.append("#endif // PUZZLES_DATA_H")

    with open("puzzles_data.h", "w") as f:
        f.write("\n".join(out) + "\n")
    print("Wrote puzzles_data.h", file=sys.stderr)


if __name__ == "__main__":
    main()
