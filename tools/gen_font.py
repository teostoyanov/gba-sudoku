#!/usr/bin/env python3
"""
Rasterizes PIL's built-in bitmap font (a true pixel font, not antialiased
vector) into 8x8 1bpp glyphs for ASCII 32..95, and emits a C header with
the glyph bitmaps (8 bytes per glyph, 1 bit per pixel, MSB = leftmost px).

This gives deterministic, visually-verified glyphs instead of hand-typed
bit patterns recalled from memory.
"""
from PIL import Image, ImageDraw, ImageFont

FIRST = 32    # space
LAST = 126    # '~' (covers full printable ASCII incl. '|')
CROP_X0, CROP_Y0 = 0, 2
W, H = 8, 8

f = ImageFont.load_default()

glyphs = []
ascii_art = []
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    img = Image.new('L', (16, 16), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), ch, font=f, fill=255)
    rows = []
    art = []
    for y in range(H):
        byte = 0
        line = ""
        for x in range(W):
            px = img.getpixel((CROP_X0 + x, CROP_Y0 + y))
            on = 1 if px > 128 else 0
            byte = (byte << 1) | on
            line += "#" if on else "."
        rows.append(byte)
        art.append(line)
    glyphs.append(rows)
    ascii_art.append((ch, art))

# Print a visual proof for a sample so it can be eyeballed before trusting it.
sample = "SUDOKU0123:-=#|+AMNW"
with open("font_preview.txt", "w") as pf:
    for ch in sample:
        code = ord(ch)
        if FIRST <= code <= LAST:
            _, art = ascii_art[code - FIRST]
            pf.write(f"'{ch}' (0x{code:02X}):\n")
            for line in art:
                pf.write("  " + line + "\n")
            pf.write("\n")

out = []
out.append("// Auto-generated by tools/gen_font.py from PIL's built-in bitmap font.")
out.append("// 8x8 1bpp glyphs for ASCII 32.._95. DO NOT EDIT BY HAND.")
out.append("#ifndef FONT_DATA_H")
out.append("#define FONT_DATA_H")
out.append("")
out.append("#define FONT_FIRST_CHAR 32")
out.append("#define FONT_LAST_CHAR  126")
out.append("#define FONT_NUM_GLYPHS (FONT_LAST_CHAR - FONT_FIRST_CHAR + 1)")
out.append("")
out.append("// [glyph][row] -> 8-bit row, bit7=leftmost pixel")
out.append("static const unsigned char font8x8[FONT_NUM_GLYPHS][8] = {")
for i, rows in enumerate(glyphs):
    code = FIRST + i
    ch = chr(code)
    comment = ch if ch.isprintable() and ch != '\\' else '?'
    row_str = ",".join(str(b) for b in rows)
    out.append(f"  {{{row_str}}}, // 0x{code:02X} '{comment}'")
out.append("};")
out.append("")
out.append("#endif // FONT_DATA_H")

with open("font_data.h", "w") as fh:
    fh.write("\n".join(out) + "\n")

print("Wrote font_data.h and font_preview.txt")
